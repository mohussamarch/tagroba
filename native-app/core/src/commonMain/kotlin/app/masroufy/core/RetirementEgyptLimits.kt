package app.masroufy.core

/**
 * «حاسبة التقاعد» — مصر: **الحد الأدنى والأقصى لأجر الاشتراك** + أرقام اللائحة التنفيذية اللي بتغيّر حسبة المعاش (OVERRIDES §69.8).
 * القرش = الوحدة الصغرى (1 جنيه = 100 قرش). أعداد صحيحة بس.
 *
 * **المصادر (كل رقم اتقرا مرتين لوحده والقرايتين اتطابقوا — 55 بند، صفر اختلاف):**
 * - **اللائحة التنفيذية** — قرار رئيس مجلس الوزراء 2437 لسنة 2021، الجريدة الرسمية العدد 38 مكرر (ب) في 2021-09-28
 *   (صورة الجريدة على manshurat.org/node/74436 — ثقة **A−**). اتقرت من صور الصفحات:
 *   - **م53 (ص46):** من 2020-01-01 الحد الأدنى **1,000** والأقصى **7,000** جنيه في الشهر · يزيدوا **15%** أول يناير كل سنة على رقم
 *     ديسمبر اللي قبله **لمدة سبع سنين**، وبعدها **بنسبة التضخم** · «يراعى **جبر** الحدين … إلى أقرب مائة جنيه».
 *   - **م105 ثالثًا (ص76):** (4) المعاش ما يقلش عن 65% من الحد الأدنى لأجر الاشتراك يوم الاستحقاق «**وبما لا يقل عن 900 جنيه**» ·
 *     «وفي جميع الأحوال يتعين ألا يزيد إجمالي المعاش على (**80%**) من **الحد الأقصى لأجر الاشتراك** في تاريخ الاستحقاق» (وده كمان
 *     آخر فقرة في م24 من القانون نفسه — ص30 من ملف NOSI، ثقة A).
 *   - **م102(7)(ب) (ص70):** شرط المبكر 50% من أجر التسوية الأخير و**65% من الحد الأدنى لأجر الاشتراك** (من غير الـ900).
 * - **أرقام كل سنة من أخبار الهيئة القومية للتأمين الاجتماعي الرسمية (nosi.gov.eg — ثقة A):**
 *   2021-11-27 (1,200) · 2022-01-04 (1,200/8,100 ⇒ 1,400/9,400) · 2023-12-17 (1,700/10,900 ⇒ 2,000/12,600) · 2025-11-30 (2,300/14,500 ⇒ 2,700/16,700).
 *
 * **فحص اتساق (مش مصدر):** قاعدة م53 بـ«جبر» = **لفوق لأقرب 100** بتطلّع أرقام الهيئة 2021–2026 بالظبط، وبالتقريب لأقرب 100 بتغلط من 2022
 * (9,300 بدل 9,400) ⇒ «جبر» = لفوق. وأرقام الهيئة للحد الأدنى/الأقصى **للمعاش** = 65% / 80% من الحدين بالظبط (مثلًا 2026: 1,755 / 13,360).
 *
 * **اللي مش هنا (والسبب):**
 * - **2027 وبعدها:** 2027 لسه ما اتعلنتش (القاعدة بتقول 3,200 / 19,300 بس ده حساب مش رقم معلن)، ومن 2028 الزيادة **بالتضخم** اللي
 *   الهيئة بتحدده ⇒ مش معروف. ⚠️ **كل يناير يتضاف سطر** من خبر الهيئة الرسمي.
 * - **نسب التضخم لأجر التسوية:** القانون م1(6) بيقول «المتوسط الشهري لمعدلات التضخم عن سنة سابقة … يوليو … بقرار من رئيس الهيئة»،
 *   واللائحة م1(7) بتقول «التغير النسبي … ويحدد في شهر أبريل» — والقرارات نفسها بالأرقام **ما لقيناهاش منشورة** ⇒ أجر التسوية فاضل مدخل.
 * - **جدول التدرّج لسن الشيخوخة (م41):** اللائحة م303(3) بتقول بس إن الوزير «يعرض مشروع قرار» — **القرار ما لقيناهوش** (اللي في الأخبار
 *   «61 في 2032 … 65 في 2040» كلام مستشار الوزارة للبرلمان 2019 — ثقة C) ⇒ السن فاضل مدخل.
 * - **زيادة م163 من القانون** («الفرق بين 450 جنيهًا و33% من إجمالي المعاش» — ص98، ومعاها م105 ثالثًا(2) وم106 في اللائحة): النص مش
 *   واضح هي 33% بحد أقصى 450 ولا حاجة تانية ⇒ **مش محسوبة** والشاشة بتقول كده ([TextKey.CALC_EGYPT_ART163_NOTE]) — سؤال للمالك.
 */

/** الحد الأدنى والأقصى لأجر الاشتراك الشهري في سنة [year] (بالقرش). */
data class EgyptContributionWageLimits(val year: Int, val minMinor: Halalas, val maxMinor: Halalas)

/** م105 ثالثًا(4) من اللائحة: المعاش «لا يقل عن 900 جنيه». */
const val EG_MIN_PENSION_NUMERIC_MINOR: Halalas = 90_000L

/** م24 آخر فقرة (القانون) + م105 (اللائحة): المعاش ≤ 80% من الحد الأقصى لأجر الاشتراك يوم الاستحقاق. */
const val EG_MAX_PENSION_OF_MAX_WAGE_BP = 8_000L

/** الأرقام الرسمية بالسنة (اقرا KDoc الملف للمصدر). السطر يتضاف أول كل سنة من خبر الهيئة — ما يتحسبش من القاعدة. */
internal val EG_CONTRIBUTION_WAGE_LIMITS: List<EgyptContributionWageLimits> = listOf(
    EgyptContributionWageLimits(2020, 100_000L, 700_000L), // اللائحة م53 (A−)
    EgyptContributionWageLimits(2021, 120_000L, 810_000L), // NOSI 2021-11-27 + 2022-01-04 «بدلاً من» (A)
    EgyptContributionWageLimits(2022, 140_000L, 940_000L), // NOSI 2022-01-04 (A)
    EgyptContributionWageLimits(2023, 170_000L, 1_090_000L), // NOSI 2023-12-17 «بدلاً من» (A)
    EgyptContributionWageLimits(2024, 200_000L, 1_260_000L), // NOSI 2023-12-17 (A)
    EgyptContributionWageLimits(2025, 230_000L, 1_450_000L), // NOSI 2025-11-30 «من» (A)
    EgyptContributionWageLimits(2026, 270_000L, 1_670_000L), // NOSI 2025-11-30 (A)
)

/** الحدين يوم [date] (السنة الميلادية — بيتغيروا أول يناير). سنة مش في الجدول (قبل 2020 أو لسه ما اتعلنتش) ⇒ null. */
fun egyptContributionWageLimits(date: IsoDate): EgyptContributionWageLimits? {
    val year = date.take(4).toIntOrNull() ?: return null
    return EG_CONTRIBUTION_WAGE_LIMITS.firstOrNull { it.year == year }
}

/** آخر سنة معلنة رسميًا — **اقتراح** يتعرض للمستخدم بس (رقم سنة معينة، مش رقم يوم التقاعد). */
fun egyptLatestContributionWageLimits(): EgyptContributionWageLimits = EG_CONTRIBUTION_WAGE_LIMITS.last()
