package app.masroufy.core

/**
 * سياسة الحساب وقت العرض — مين بيتحسب دخل، وفي أنهي شهر. **مفيش حاجة بتتكتب** في التخزين بسببها (التاريخ والنوع زي ما هم).
 *
 * - [LEGACY] = التطبيق القديم بالحرف (OVERRIDES §18): الداخل اللي مالوش اقتراح بيتحسب «راتب» تقديري، وكل عملية في شهر تاريخها.
 *   ملفات المرجع (golden) اتولدت منها، فالاختبارات اللي بتقارن بيها بتشتغل عليها صراحةً.
 * - [OWNER_2026_10] = قرارات المالك 2026-10-08 (§75-1 و§75-3): الداخل اللي نوعه مش معروف **«مستني» برّه الدخل** لحد ما يتأكد،
 *   والراتب اللي نزل قبل أول الشهر المالي بشوية **بيتحسب للشهر الجديد** ([SALARY_EARLY_DAYS]).
 *
 * ليه متغير عام زي [Texts.arabicVariant] ومش مدخل في كل حالة استخدام: السياسة اختيار للتطبيق كله (مش لشاشة)، و`withEstimatedKinds`
 * بيتنادى من عشر أماكن (منهم `core/Projects.kt`) — المدخل كان هيلف على كل الشاشات من غير ما يفرق. الدوال النقية بتاخدها مدخل
 * اختياري (الافتراضي = الحالية) عشان اختباراتها ما تلمسش المتغير.
 */
enum class EstimatePolicy {
    LEGACY,
    OWNER_2026_10,
    ;

    companion object {
        /** السياسة الشغالة. الاختبار اللي بيغيّرها لازم يرجّعها في `@AfterTest` (زي اللغة). */
        var current: EstimatePolicy = OWNER_2026_10
    }
}
