package app.masroufy.core

/**
 * عقد C0 — «يسأل» في قرارات §75 و§77 = **سؤال جوه التطبيق** على العملية أو الرسالة + سطر في عدّ «محتاجة تأكيد» والتذكير
 * الأسبوعي (§75-15). مفيش إشعار جوال جديد. كل شريحة بتطلّع أسئلتها من مصدر (`AskSource`)، والعدّ بيجمعهم.
 */

/** نوع السؤال — **بترتيب الأولوية** (الأدق الأول): لو العملية عليها كذا سؤال، الأول هو اللي بيتعرض. */
enum class AskKind {
    /** §75-12: شراء بعملة أجنبية ⇒ المبلغ بالعملة المحلية كام؟ */
    FOREIGN_LOCAL_AMOUNT,

    /** §77-D: «التحويل رجع» وما لقيناش العملية الأصلية ⇒ استرداد مقترح؟ */
    REVERSAL_CHECK,

    /** §75-6: استرداد مقترح ⇒ أكّده. */
    REFUND_CONFIRM,

    /** §75-2: رسالة راتب من غير اسم الجهة ⇒ «ده راتبك؟» مرة لكل مرسل. */
    IS_SALARY,

    /** §75-9: سداد سلفة ⇒ يسأل. */
    DEBT_REPAYMENT,

    /** §75-5: حوالة لشخص مربوط ⇒ «سلفة ولا دعم؟» كل مرة. */
    LOAN_OR_SUPPORT,

    /** §75-8: قسط أو جمعية ⇒ نربطه؟ */
    DUE_LINK,

    /** §75-1: داخل نوعه مش معروف ⇒ «مستني» برّه الدخل لحد ما يتأكد. */
    INCOMING_KIND,

    /** رسالة بنك مستنية تأكيدك (أي سبب تاني). */
    SMS_WAITING,
}

/** سؤال واحد مستني المالك. [transactionId] لو على عملية متسجلة · [messageId] لو على رسالة لسه في الصندوق. */
data class PendingAsk(
    val kind: AskKind,
    val spaceId: String,
    val transactionId: Id? = null,
    val messageId: String? = null,
    val date: IsoDate? = null,
)
