/**
 * بيشغّل الكود بكل نصوص العرض: العربي **بالنسختين** (فصحى · مصري — OVERRIDES §66) والإنجليزي، وبيرجّع اللغة والنسخة زي ما كانوا.
 * لاختبارات «في كل لغة» زي نص شاشة القفل — عشان أي نسخة جديدة تتفحص لوحدها من غير ما حد يفتكر.
 */
fun forEachTextVariant(block: (label: String) -> Unit) {
    val language = Texts.language
    val variant = Texts.arabicVariant
    try {
        for (v in ArabicVariant.entries) {
            Texts.language = Language.AR
            Texts.arabicVariant = v
            block("AR-$v")
        }
        Texts.language = Language.EN
        Texts.arabicVariant = ArabicVariant.MSA
        block("EN")
    } finally {
        Texts.language = language
        Texts.arabicVariant = variant
    }
}

