/**
 * أشكال مصرية بالقاعدة: هـ+فعل للمستقبل (هتدفع · هيتحسب — إلا «هيئة») · بتتـ وبيتـ+فعل (بتتسجل · بيتحسب) · النفي بـ«ش» في الآخر
 * (اتثبتش · بيدخلش · ماتعرفش).
 */
private val EGYPTIAN_FORM = Regex("^(هت|بتت|بيت..|هي(?!ئ)..)|^(ات|بت|بي|ما)..+ش$")

/** الكلمات المصرية في نص (بعد شيل التشكيل والتطويل) — للفحص إن الفصحى ما فيهاش لهجة. */
fun egyptianTokens(text: String): List<String> {
    val plain = text.filter { it !in 'ً'..'ْ' && it != 'ٰ' && it != 'ـ' }
    return Regex("[ء-ي]+").findAll(plain).map { it.value }
        .filter { it in EGYPTIAN_ONLY_WORDS || EGYPTIAN_FORM.containsMatchIn(it) }
        .toList()
}
