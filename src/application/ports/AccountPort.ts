/**
 * الحساب اللي داخل دلوقتي — لقسم «الحساب» في الإعدادات (OVERRIDES §26).
 * تغيير كلمة السر بيتم بإيميل إعادة تعيين: التطبيق ما بيستلمش كلمة سر ولا بيكتبها.
 */
export interface AccountPort {
  /** إيميل الحساب الداخل؛ null لو مالوش إيميل. */
  email(): string | null
  /** بيبعت إيميل تغيير كلمة السر لإيميل الحساب نفسه. بيرمي خطأ بلغة المستخدم لو ما اتبعتش. */
  sendPasswordReset(): Promise<void>
}
